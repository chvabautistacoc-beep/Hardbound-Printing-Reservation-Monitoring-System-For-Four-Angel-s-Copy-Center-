    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String emailInput = email.getText().trim();
        String passwordInput = new String(password.getPassword()).trim();
        
        if (emailInput.isEmpty() || passwordInput.isEmpty()) {
            JOptionPane.showMessageDialog(
                null,
                "Please enter email and password fields.",
                "Missing Data!",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String sql = "SELECT * FROM tbl_users WHERE email = ? AND password = ?";

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            java.sql.Connection conn = DatabaseConnection.getConnection();
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            
            pst.setString(1, emailInput);
            pst.setString(2, passwordInput);

            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                int dbUserId = rs.getInt("user_id");
                String dbFirstName = rs.getString("f_name");
                String name = dbFirstName.substring(0, 1).toUpperCase() + dbFirstName.substring(1).toLowerCase();
                JOptionPane.showMessageDialog(
                    null,
                    "Login successful! Welcome back, " + name + ".",
                    "Access Granted!",
                    JOptionPane.INFORMATION_MESSAGE
                );
                UserSession.setUser(dbUserId, dbFirstName);
                int state = this.getExtendedState();
                student_dashboard dashboardFrame = new student_dashboard();
                dashboardFrame.setExtendedState(state);
                dashboardFrame.setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(
                    null,
                    "Invalid email address or password.",
                    "Access Denied!",
                    JOptionPane.ERROR_MESSAGE
                );
            }
            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                null,
                "Database error: " + e.getMessage(),
                "System Error!",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jButton1ActionPerformed

