    private void confirm_paymentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirm_paymentActionPerformed
        if (!confirm_agreement.isSelected()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please confirm the agreement first.",
                    "Confirmation Required",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String referenceNumber = referencee_number.getText().trim();

        if (referenceNumber.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please enter your transaction reference number.",
                    "Reference Number Required",
                    JOptionPane.WARNING_MESSAGE
            );
            referencee_number.requestFocus();
            return;
        }
        
        if (referenceNumber.length() > 15) {
            JOptionPane.showMessageDialog(
                null,
                "Reference number must not exceed 15 characters.",
                "Invalid Reference Number!",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (paymentMethod == null
        || (!paymentMethod.equalsIgnoreCase("GCash")
        && !paymentMethod.equalsIgnoreCase("Maya"))) {
            JOptionPane.showMessageDialog(
                    this,
                    "Invalid payment method.",
                    "Payment Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Payment Method: " + paymentMethod + "\n\n"
                + "I confirm that my transaction reference number is correct "
                + "and that I have double-checked it.\n\n"
                + "If the reference number is invalid, my reservation may be "
                + "flagged as Rejected after the admin reviews it.\n\n"
                + "Do you want to proceed?",
                "Confirm Payment Details",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        if (reservationForm.saveReservation(
            paymentMethod,
            referenceNumber,
            "Partial Payment",
            "Pending",
            "Partially Paid",
            "Not Started")) {
            JOptionPane.showMessageDialog(
                    this,
                    "Your reservation has been submitted successfully!\n\n"
                    + "Payment Method: " + paymentMethod
                    + "\nReference Number: " + referenceNumber,
                    "Reservation Submitted",
                    JOptionPane.INFORMATION_MESSAGE
            );

            reservationForm.resetFrame();
            dispose();

        }
    }//GEN-LAST:event_confirm_paymentActionPerformed

