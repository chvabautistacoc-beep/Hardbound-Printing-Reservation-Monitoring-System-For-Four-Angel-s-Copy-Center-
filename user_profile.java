    private void enable_change_personalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_enable_change_personalActionPerformed
        if (enable_change_personal.isSelected()) {
            first_name.setEditable(true);
            last_name.setEditable(true);
            email.setEditable(true);
            phone_number.setEditable(true);

        } else {
            String sql = "SELECT f_name, l_name, email, phone_number "
                       + "FROM tbl_users WHERE user_id = ?";

            try (java.sql.Connection conn = DatabaseConnection.getConnection();
                 java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

                pst.setInt(1, UserSession.getUserId());

                try (java.sql.ResultSet rs = pst.executeQuery()) {
                    if (rs.next()) {
                        first_name.setText(rs.getString("f_name"));
                        last_name.setText(rs.getString("l_name"));
                        email.setText(rs.getString("email"));
                        phone_number.setText(rs.getString("phone_number"));
                    }
                }

            } catch (java.sql.SQLException e) {
                JOptionPane.showMessageDialog(
                    this,
                    "Error loading current details: " + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }

            first_name.setEditable(false);
            last_name.setEditable(false);
            email.setEditable(false);
            phone_number.setEditable(false);
        }
    }//GEN-LAST:event_enable_change_personalActionPerformed

    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        boolean changePersonal = enable_change_personal.isSelected();

        if (!changePersonal) {
            JOptionPane.showMessageDialog(
                this,
                "Please enable change Personal Information to update.",
                "No Changes Selected",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String fName = first_name.getText().trim();
        String lName = last_name.getText().trim();
        String userEmail = email.getText().trim();
        String phone = phone_number.getText().trim();

        int userId = UserSession.getUserId();

        if (fName.isEmpty() || lName.isEmpty()
                || userEmail.isEmpty() || phone.isEmpty()) {

            JOptionPane.showMessageDialog(
                this,
                "Please fill in all personal information fields.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        
        if (fName.length() > 15) {
            JOptionPane.showMessageDialog(
                null,
                "First name must not exceed 15 characters.",
                "Invalid First Name!",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        
        if (!fName.matches("\\p{L}+")) {
            JOptionPane.showMessageDialog(
                this,
                "First name must contain letters only. No spaces, numbers, or symbols.",
                "Invalid First Name",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        
        if (lName.length() > 15) {
            JOptionPane.showMessageDialog(
                null,
                "Last name must not exceed 15 characters.",
                "Invalid Last Name!",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }
        
        if (!lName.matches("\\p{L}+")) {
            JOptionPane.showMessageDialog(
                this,
                "Last name must contain letters only. No spaces, numbers, or symbols.",
                "Invalid Last Name",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!phone.matches("09\\d{9}")) {
            JOptionPane.showMessageDialog(
                this,
                "Phone number must start with 09 and contain exactly 11 digits.",
                "Invalid Phone Number",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String emailRegex =
            "^[A-Za-z0-9]+([._%+-][A-Za-z0-9]+)*"
          + "@[A-Za-z0-9-]+(\\.[A-Za-z0-9-]+)*\\.[A-Za-z]{2,}$";

        if (!userEmail.matches(emailRegex)) {
            JOptionPane.showMessageDialog(
                this,
                "Please enter a valid email address.",
                "Invalid Email",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try (java.sql.Connection conn =
                DatabaseConnection.getConnection()) {

            conn.setAutoCommit(false);

            try {
                String checkEmailSql =
                    "SELECT user_id FROM tbl_users "
                  + "WHERE email = ? AND user_id <> ?";

                try (java.sql.PreparedStatement pst =
                        conn.prepareStatement(checkEmailSql)) {

                    pst.setString(1, userEmail);
                    pst.setInt(2, userId);

                    try (java.sql.ResultSet rs = pst.executeQuery()) {
                        if (rs.next()) {
                            throw new Exception(
                                "This email address is already in use. "
                              + "Please use another email."
                            );
                        }
                    }
                }

                String checkUserSql =
                    "SELECT f_name, l_name, email, phone_number "
                  + "FROM tbl_users WHERE user_id = ?";

                boolean userFound = false;
                boolean hasChanges = false;

                try (java.sql.PreparedStatement pst =
                        conn.prepareStatement(checkUserSql)) {

                    pst.setInt(1, userId);

                    try (java.sql.ResultSet rs = pst.executeQuery()) {
                        if (rs.next()) {
                            userFound = true;

                            hasChanges =
                                !java.util.Objects.equals(
                                    fName, rs.getString("f_name"))
                                || !java.util.Objects.equals(
                                    lName, rs.getString("l_name"))
                                || !java.util.Objects.equals(
                                    userEmail, rs.getString("email"))
                                || !java.util.Objects.equals(
                                    phone, rs.getString("phone_number"));
                        }
                    }
                }

                if (!userFound) {
                    throw new Exception("User account not found.");
                }

                if (!hasChanges) {
                    conn.rollback();

                    JOptionPane.showMessageDialog(
                        this,
                        "No changes detected in your personal information.",
                        "No Changes",
                        JOptionPane.INFORMATION_MESSAGE
                    );
                    return;
                }

                String updateSql =
                    "UPDATE tbl_users SET f_name = ?, l_name = ?, "
                  + "email = ?, phone_number = ? WHERE user_id = ?";

                try (java.sql.PreparedStatement pst =
                        conn.prepareStatement(updateSql)) {

                    pst.setString(1, fName);
                    pst.setString(2, lName);
                    pst.setString(3, userEmail);
                    pst.setString(4, phone);
                    pst.setInt(5, userId);

                    if (pst.executeUpdate() == 0) {
                        throw new Exception(
                            "Unable to update personal information."
                        );
                    }
                }

                conn.commit();

                enable_change_personal.setSelected(false);

                first_name.setEditable(false);
                last_name.setEditable(false);
                email.setEditable(false);
                phone_number.setEditable(false);
                UserSession.setUser(UserSession.getUserId(), fName);
                name.setText("Hi, " + fName.substring(0, 1).toUpperCase() + fName.substring(1).toLowerCase());
                JOptionPane.showMessageDialog(
                    this,
                    "Personal information updated successfully!",
                    "Update Success",
                    JOptionPane.INFORMATION_MESSAGE
                );

            } catch (Exception e) {
                conn.rollback();

                JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Update Failed",
                    JOptionPane.ERROR_MESSAGE
                );

            } finally {
                conn.setAutoCommit(true);
            }

        } catch (java.sql.SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Database error: " + e.getMessage(),
                "System Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jButton7ActionPerformed

    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed

        if (!enable_change_password.isSelected()) {
            JOptionPane.showMessageDialog(
                this,
                "Please enable password editing first.",
                "No Changes Selected",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String newPass = new String(new_password.getPassword());
        int userId = UserSession.getUserId();

        if (newPass.trim().isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Please enter your new password.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (newPass.length() < 8) {
            JOptionPane.showMessageDialog(
                this,
                "Your new password must contain at least 8 characters.",
                "Invalid Password",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try (java.sql.Connection conn =
                DatabaseConnection.getConnection()) {

            conn.setAutoCommit(false);

            try {
                String checkPasswordSql =
                    "SELECT password FROM tbl_users WHERE user_id = ?";

                String savedPassword;

                try (java.sql.PreparedStatement pst =
                        conn.prepareStatement(checkPasswordSql)) {

                    pst.setInt(1, userId);

                    try (java.sql.ResultSet rs = pst.executeQuery()) {
                        if (!rs.next()) {
                            throw new Exception("User account not found.");
                        }

                        savedPassword = rs.getString("password");
                    }
                }

                if (java.util.Objects.equals(newPass, savedPassword)) {
                    throw new Exception(
                        "Your new password must be different from your current password."
                    );
                }

                String updatePasswordSql =
                    "UPDATE tbl_users SET password = ? WHERE user_id = ?";

                try (java.sql.PreparedStatement pst =
                        conn.prepareStatement(updatePasswordSql)) {

                    pst.setString(1, newPass);
                    pst.setInt(2, userId);

                    if (pst.executeUpdate() == 0) {
                        throw new Exception(
                            "Failed to update your password."
                        );
                    }
                }

                conn.commit();

                enable_change_password.setSelected(false);

                current_password.setText(newPass);
                new_password.setText("");

                current_password.setEditable(false);
                new_password.setEditable(false);

                current_password.setEchoChar('*');
                new_password.setEchoChar('*');

                JOptionPane.showMessageDialog(
                    this,
                    "Password updated successfully!",
                    "Update Success",
                    JOptionPane.INFORMATION_MESSAGE
                );

            } catch (Exception e) {
                conn.rollback();

                JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Update Failed",
                    JOptionPane.ERROR_MESSAGE
                );

            } finally {
                conn.setAutoCommit(true);
            }

        } catch (java.sql.SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Database error: " + e.getMessage(),
                "System Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jButton8ActionPerformed

