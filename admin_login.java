    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String emailInput = email.getText().trim();
        String passwordInput = new String(password.getPassword()).trim();
        
        
        String AdminEmail = "admin@gmail.com";
        String AdminPassword = "admin123";

        String enteredEmail = email.getText().trim();
        String enteredPassword = new String(password.getPassword());

        if (enteredEmail.equals(AdminEmail)
                && enteredPassword.equals(AdminPassword)) {

            JOptionPane.showMessageDialog(
                this,
                "Login Successful, Welcome back Admin!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
            );

            int state = this.getExtendedState();
            admin_dashboard dashboardFrame = new admin_dashboard();
            dashboardFrame.setExtendedState(state);
            dashboardFrame.setVisible(true);
            this.dispose();

        } else {
            JOptionPane.showMessageDialog(
                this,
                "Invalid email or password.",
                "Login Failed",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jButton1ActionPerformed

